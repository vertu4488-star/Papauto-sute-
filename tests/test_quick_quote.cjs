const assert=require("node:assert/strict");
const {quote,fromLot}=require("../papauto-quick-quote.js");
const x={market:"japan",currency:"JPY",restricted:false,type:"ice",fuel:"gasoline",engine:1300,power:95,year:2022,name:"Honda Fit",amount:800000};
const fx={date:"2026-11-25",rub_per_jpy:.5,rub_per_usd:80,rub_per_eur:90};
const tariffs={table:{"Новосибирск":{compact:{estimate:120000}}}};
const opts={clearDate:"2026-11-25",eligibility:"yes"};
const q=quote(x,fx,tariffs,opts);
assert.equal(q.costs.duty,198900);
assert.equal(q.costs.util,5200);
assert.equal(q.costs.delivery,120000);
assert.equal(q.total,Object.values(q.costs).reduce((a,b)=>a+b,0));
for(const change of [{type:"hybrid"},{type:"ev"},{type:""},{fuel:"diesel"},{fuel:""},{engine:1901},{power:null},{year:2023},{restricted:true},{market:"china"}])assert.equal(quote({...x,...change},fx,tariffs,opts).total,null);
assert.equal(quote(x,{...fx,fallback:true},tariffs,opts).total,null);
assert.equal(quote(x,fx,tariffs,{...opts,eligibility:""}).total,null);
assert.equal(quote(x,fx,null,opts).total,null);
assert.equal(fromLot({fuel_type:"gasoline",engine_type:"ice"}).fuel,"gasoline");
assert.equal(fromLot({engine_type:"ice"}).fuel,"");
assert.equal(fromLot({fuel_type:"diesel",engine_type:"ice"}).fuel,"diesel");
assert.equal(fromLot({fuel_type:"gasoline",trim:"Hybrid X"}).fuel,"excluded");
console.log("Quick quote tests passed");
